"""Run every experiment of the project.

Outputs:
  figures/*.png and figures/*.pdf   figures for the README and the LaTeX report
  results.md                        all measured numbers
  report/generated.tex              the same numbers as LaTeX tables and macros (used by rapport.tex)

Usage (from the project root):
    python experiments/run_all.py
"""

import os
import sys
import time

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from pcasvd import compression as comp, data, linalg, pca  # noqa: E402

FIG = os.path.join(ROOT, "figures")
os.makedirs(FIG, exist_ok=True)
os.makedirs(os.path.join(ROOT, "report"), exist_ok=True)

DARK, PURPLE, ORANGE, GREY = "#171717", "#9B7BF7", "#FE8A5D", "#9CA3AF"
CULTIVARS = {1: PURPLE, 2: ORANGE, 3: DARK}
plt.rcParams.update({
    "figure.dpi": 130, "savefig.dpi": 130, "font.size": 10,
    "axes.spines.top": False, "axes.spines.right": False,
    "axes.grid": True, "grid.alpha": 0.25, "legend.frameon": False,
})

md = ["# Results", "", "Generated by `python experiments/run_all.py`.", ""]
tex = ["% Generated by experiments/run_all.py: do not edit by hand.", ""]


def macro(name, value):
    tex.append("\\newcommand{\\%s}{%s}" % (name, value))


def table(name, rows):
    tex.append("\\newcommand{\\%s}{%%" % name)
    tex.extend(rows)
    tex.append("}")


def save(fig, name):
    fig.tight_layout()
    for ext in ("png", "pdf"):
        fig.savefig(os.path.join(FIG, f"{name}.{ext}"))
    plt.close(fig)
    print("saved figures/%s.png/.pdf" % name)


def sci(x, digits=1):
    m, e = f"{x:.{digits}e}".split("e")
    return f"{m.replace('.', '{,}')} \\times 10^{{{int(e)}}}"


def fr(x, digits=2):
    return f"{x:.{digits}f}".replace(".", "{,}")


# --------------------------------------------------------------------- 1. Wine
def experiment_wine():
    X, cultivar, names = data.load_wine()
    n, p = X.shape
    a = pca.pca_covariance(X)
    b = pca.pca_svd(X)
    var_diff = float(np.max(np.abs(a.variances - b.variances)))
    axis_cos = np.abs(np.sum(a.components * b.components, axis=0))
    ratio = a.explained_ratio
    cum = np.cumsum(ratio)
    kaiser = int(np.sum(a.variances > 1))

    md.extend(["## 1. PCA of the Wine dataset (178 wines, 13 standardised variables)", "",
               "| Axis | Eigenvalue (covariance + Jacobi) | sigma^2/(n-1) (SVD) | Explained | Cumulative |", "|---|---|---|---|---|"])
    rows = []
    for j in range(p):
        md.append(f"| PC{j + 1} | {a.variances[j]:.4f} | {b.variances[j]:.4f} | {100 * ratio[j]:.1f} % | {100 * cum[j]:.1f} % |")
        if j < 6:
            rows.append(f"$\\mathrm{{CP}}_{j + 1}$ & {fr(a.variances[j], 4)} & {fr(b.variances[j], 4)} & {fr(100 * ratio[j], 1)}\\,\\% & {fr(100 * cum[j], 1)}\\,\\% \\\\")
    table("tableEigen", rows)
    md.extend(["", f"Largest difference between the two routes: variances {var_diff:.1e}, axes |cos| >= {axis_cos.min():.12f}.",
               f"Kaiser criterion (eigenvalue > 1): {kaiser} components.", ""])
    macro("varDiff", sci(var_diff))
    macro("expOne", fr(100 * ratio[0], 1))
    macro("expTwo", fr(100 * ratio[1], 1))
    macro("cumTwo", fr(100 * cum[1], 1))
    macro("cumFive", fr(100 * cum[4], 1))
    macro("nKaiser", str(kaiser))

    # check against scikit-learn if it is installed (it is only used for this check)
    try:
        from sklearn.decomposition import PCA as SkPCA
        Z = (X - X.mean(0)) / X.std(0, ddof=1)
        sk = SkPCA().fit(Z)
        sk_diff = float(np.max(np.abs(sk.explained_variance_ - a.variances)))
        md.append(f"Check against scikit-learn PCA: max variance difference {sk_diff:.1e}.")
        macro("skDiff", sci(sk_diff))
    except ImportError:
        macro("skDiff", "--")

    # raw data: one variable dominates
    raw = pca.pca_covariance(X, standardize=False)
    top = names[int(np.argmax(np.abs(raw.components[:, 0])))]
    md.extend(["", f"Without standardisation, PC1 explains {100 * raw.explained_ratio[0]:.1f} % and is almost exactly the variable '{top}' (values around 1000).", ""])
    macro("rawOne", fr(100 * raw.explained_ratio[0], 1))
    macro("rawTop", top.replace("_", "\\_"))

    # separation of the cultivars in the first plane: leave-one-out nearest-centroid
    S2 = a.scores[:, :2]
    correct = 0
    for i in range(n):
        mask = np.arange(n) != i
        cents = {c: S2[mask & (cultivar == c)].mean(axis=0) for c in (1, 2, 3)}
        pred = min(cents, key=lambda c: np.sum((S2[i] - cents[c]) ** 2))
        correct += pred == cultivar[i]
    acc = correct / n
    md.append(f"Nearest-centroid classification in the (PC1, PC2) plane, leave-one-out: {100 * acc:.1f} % of wines assigned to the right cultivar.")
    macro("nccAcc", fr(100 * acc, 1))

    # figures: scree plot and plane of the first two components
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(10, 4))
    ax1.bar(range(1, p + 1), 100 * ratio, color=PURPLE, label="explained variance")
    ax1.plot(range(1, p + 1), 100 * cum, "o-", color=ORANGE, ms=4, label="cumulative")
    ax1.set_xlabel("principal component")
    ax1.set_ylabel("% of the total variance")
    ax1.set_xticks(range(1, p + 1))
    ax1.set_title("Explained variance")
    ax1.legend()
    for c, col in CULTIVARS.items():
        sel = cultivar == c
        ax2.scatter(a.scores[sel, 0], a.scores[sel, 1], s=14, color=col, alpha=0.8, label=f"cultivar {c}")
    ax2.set_xlabel(f"PC1 ({100 * ratio[0]:.1f} %)")
    ax2.set_ylabel(f"PC2 ({100 * ratio[1]:.1f} %)")
    ax2.set_title("Wines projected on the first two components")
    ax2.legend()
    save(fig, "1_wine_pca")

    # correlation circle: corr(variable j, PC k) = v_jk sqrt(lambda_k) for standardised data
    corr = a.components[:, :2] * np.sqrt(a.variances[:2])
    corr[np.abs(corr) < 0.005] = 0.0  # avoid printing -0.00
    fig, ax = plt.subplots(figsize=(5.6, 5.6))
    t = np.linspace(0, 2 * np.pi, 200)
    ax.plot(np.cos(t), np.sin(t), color=GREY, lw=1)
    for j, name in enumerate(names):
        ax.annotate("", xy=(corr[j, 0], corr[j, 1]), xytext=(0, 0), arrowprops=dict(arrowstyle="->", color=PURPLE, lw=1.2))
        ax.text(corr[j, 0] * 1.08, corr[j, 1] * 1.08, name, fontsize=7.5, ha="center", va="center", color=DARK)
    ax.set_xlim(-1.15, 1.15)
    ax.set_ylim(-1.15, 1.15)
    ax.set_aspect("equal")
    ax.axhline(0, color=GREY, lw=0.6)
    ax.axvline(0, color=GREY, lw=0.6)
    ax.set_xlabel("correlation with PC1")
    ax.set_ylabel("correlation with PC2")
    ax.set_title("Correlation circle")
    save(fig, "2_correlation_circle")

    md.extend(["", "Correlations with the first two components:", "", "| Variable | PC1 | PC2 |", "|---|---|---|"])
    rows = []
    for j in np.argsort(-np.abs(corr[:, 0])):
        md.append(f"| {names[j]} | {corr[j, 0]:+.2f} | {corr[j, 1]:+.2f} |")
        rows.append(f"\\texttt{{{names[j].replace('_', '\\_')}}} & ${corr[j, 0]:+.2f}$ & ${corr[j, 1]:+.2f}$ \\\\".replace(".", "{,}"))
    table("tableCorr", rows)
    md.append("")


# ---------------------------------------------- 2. covariance route vs SVD route
def experiment_stability():
    eps_list = [10.0 ** -k for k in range(1, 11)]
    err_cov, err_svd = [], []
    for e in eps_list:
        # Lauchli matrix: singular values sqrt(3 + e^2), e, e
        A = np.array([[1, 1, 1], [e, 0, 0], [0, e, 0], [0, 0, e]], dtype=float)
        lam, _ = linalg.jacobi_eigen(A.T @ A)
        s_cov = np.sqrt(np.clip(lam, 0, None))
        _, s_svd, _ = linalg.jacobi_svd(A)
        err_cov.append(abs(s_cov[-1] - e) / e)
        err_svd.append(abs(s_svd[-1] - e) / e)
    fig, ax = plt.subplots(figsize=(6.4, 4))
    ax.loglog(eps_list, np.maximum(err_cov, 1e-17), "o-", color=GREY, label="eigenvalues of A^T A (covariance route)")
    ax.loglog(eps_list, np.maximum(err_svd, 1e-17), "o-", color=ORANGE, label="SVD of A")
    ax.invert_xaxis()
    ax.set_xlabel("smallest singular value epsilon")
    ax.set_ylabel("relative error on epsilon")
    ax.set_title("Forming A^T A squares the condition number")
    ax.legend(fontsize=8)
    save(fig, "3_stability")
    md.extend(["## 2. Covariance route vs SVD route: numerical accuracy", "",
               "Lauchli matrix A = [[1,1,1],[e,0,0],[0,e,0],[0,0,e]], smallest singular value e.", "",
               "| e | Relative error, eigenvalues of A^T A | Relative error, SVD |", "|---|---|---|"])
    rows = []
    for e, c, s in zip(eps_list, err_cov, err_svd):
        if e in (1e-2, 1e-4, 1e-6, 1e-8, 1e-10):
            md.append(f"| {e:.0e} | {c:.1e} | {s:.1e} |")
            rows.append(f"$10^{{{int(round(np.log10(e)))}}}$ & ${sci(c) if c > 0 else '0'}$ & ${sci(s) if s > 0 else '0'}$ \\\\")
    table("tableStability", rows)
    md.append("")


# ------------------------------------------------------------ 3. image compression
def experiment_image():
    A = data.load_image(gray=True)
    m, n = A.shape
    t0 = time.perf_counter()
    U, s, Vt = linalg.jacobi_svd(A)
    dt = time.perf_counter() - t0
    ref = np.linalg.svd(A, compute_uv=False)
    sv_err = float(np.max(np.abs(s - ref)) / ref[0])
    md.extend(["## 3. Image compression (512 x 512 grayscale photo)", "",
               f"One-sided Jacobi SVD computed in {dt:.1f} s; largest difference with NumPy's singular values: {sv_err:.1e} (relative).", "",
               "| Rank k | Stored numbers | Relative error measured | Eckart-Young formula | ||A - A_k||_2 / sigma_(k+1) | PSNR (dB) |",
               "|---|---|---|---|---|---|"])
    macro("svdTime", fr(dt, 1))
    macro("svErr", sci(sv_err))
    ks = [1, 5, 10, 20, 50, 100, 200]
    rows, max_gap = [], 0.0
    errs = {}
    for k in ks:
        Ak = linalg.low_rank(U, s, Vt, k)
        e_meas = comp.relative_error(A, Ak)
        e_th = comp.eckart_young_error(s, k)
        spec = np.linalg.norm(A - Ak, 2) / s[k]
        max_gap = max(max_gap, abs(e_meas - e_th))
        ps = comp.psnr(A, Ak)
        errs[k] = (e_meas, ps)
        md.append(f"| {k} | {100 * comp.storage_ratio(m, n, k):.1f} % | {e_meas:.4f} | {e_th:.4f} | {spec:.6f} | {ps:.1f} |")
        rows.append(f"{k} & {fr(100 * comp.storage_ratio(m, n, k), 1)}\\,\\% & {fr(e_meas, 4)} & {fr(e_th, 4)} & {fr(ps, 1)} \\\\")
    table("tableCompression", rows)
    md.extend(["", f"Largest gap between measured and theoretical error: {max_gap:.1e}.", ""])
    macro("eyGap", sci(max_gap))
    macro("psnrFifty", fr(errs[50][1], 1))
    macro("errFifty", fr(100 * errs[50][0], 1))
    macro("storeFifty", fr(100 * comp.storage_ratio(m, n, 50), 1))

    # Eckart-Young optimality: compare with another rank-k approximation (projection on k columns of A)
    kk = [1, 2, 5, 10, 20, 50, 100, 200]
    svd_err = [comp.eckart_young_error(s, k) for k in kk]
    col_err = []
    for k in kk:
        C = A[:, np.linspace(0, n - 1, k).astype(int)]
        coef = np.linalg.lstsq(C, A, rcond=None)[0]
        col_err.append(comp.relative_error(A, C @ coef))

    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(10, 4))
    ax1.semilogy(range(1, len(s) + 1), s, color=PURPLE)
    ax1.set_xlabel("index i")
    ax1.set_ylabel("singular value sigma_i")
    ax1.set_title("Singular values of the image")
    ax2.semilogy(kk, svd_err, "o-", color=ORANGE, label="truncated SVD (Eckart-Young)")
    ax2.semilogy(kk, col_err, "o-", color=GREY, label="projection on k columns of A")
    ax2.set_xscale("log")
    ax2.set_xlabel("rank k")
    ax2.set_ylabel("relative error ||A - B||_F / ||A||_F")
    ax2.set_title("No rank-k matrix does better than the SVD")
    ax2.legend()
    save(fig, "4_singular_values")

    fig, axes = plt.subplots(2, 4, figsize=(12, 6.4))
    shown = [None, 1, 5, 10, 20, 50, 100, 200]
    for ax, k in zip(axes.ravel(), shown):
        img = A if k is None else np.clip(linalg.low_rank(U, s, Vt, k), 0, 1)
        ax.imshow(img, cmap="gray", vmin=0, vmax=1)
        ax.set_xticks([])
        ax.set_yticks([])
        ax.grid(False)
        if k is None:
            ax.set_title("original (512 x 512)", fontsize=9)
        else:
            ax.set_title(f"rank {k}: {100 * comp.storage_ratio(m, n, k):.1f} % of the data, PSNR {errs.get(k, (0, comp.psnr(A, img)))[1]:.1f} dB", fontsize=8)
    save(fig, "5_compression")

    # colour version: one SVD per channel
    C = data.load_image(gray=False)
    chans = [linalg.jacobi_svd(C[:, :, c]) for c in range(3)]
    fig, axes = plt.subplots(1, 4, figsize=(12, 3.4))
    for ax, k in zip(axes, [None, 10, 30, 80]):
        img = C if k is None else np.clip(np.dstack([linalg.low_rank(*ch, k) for ch in chans]), 0, 1)
        ax.imshow(img)
        ax.set_xticks([])
        ax.set_yticks([])
        ax.grid(False)
        ax.set_title("original" if k is None else f"rank {k} per channel, PSNR {comp.psnr(C, img):.1f} dB", fontsize=9)
    save(fig, "6_compression_color")


if __name__ == "__main__":
    experiment_wine()
    experiment_stability()
    experiment_image()
